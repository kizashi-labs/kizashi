// ─── macOS File Quarantine ────────────────────────────────────

type DarwinFileQuarantine struct {
	quarantineDir string
	mu            sync.Mutex
	index         map[string]*collector.QuarantinedFile
}

func NewDarwinFileQuarantine(dir string) *DarwinFileQuarantine {
	return &DarwinFileQuarantine{
		quarantineDir: dir,
		index:         make(map[string]*collector.QuarantinedFile),
	}
}

func (q *DarwinFileQuarantine) Quarantine(path string) (string, error) {
	q.mu.Lock()
	defer q.mu.Unlock()

	id := generateDarwinID()
	destPath := fmt.Sprintf("%s/%s.quarantine", q.quarantineDir, id)

	// Move file
	if err := runPF("mv", path, destPath); err != nil {
		return "", fmt.Errorf("move to quarantine: %w", err)
	}

	// Strip execute bit and immutable flag
	_ = runPF("chmod", "000", destPath)
	// Add macOS quarantine extended attribute
	_ = runPF("xattr", "-w", "com.apple.quarantine",
		"0083;00000000;EDR-Agent;", destPath)

	q.index[id] = &collector.QuarantinedFile{
		ID:           id,
		OriginalPath: path,
	}

	return id, nil
}

func (q *DarwinFileQuarantine) Restore(quarantineID string, restorePath string) error {
	q.mu.Lock()
	defer q.mu.Unlock()

	entry, ok := q.index[quarantineID]
	if !ok {
		return fmt.Errorf("quarantine ID %s not found", quarantineID)
	}

	srcPath := fmt.Sprintf("%s/%s.quarantine", q.quarantineDir, quarantineID)
	dest := restorePath
	if dest == "" {
		dest = entry.OriginalPath
	}

	_ = runPF("chmod", "644", srcPath)
	_ = runPF("xattr", "-d", "com.apple.quarantine", srcPath)

	if err := runPF("mv", srcPath, dest); err != nil {
		return fmt.Errorf("restore file: %w", err)
	}

	delete(q.index, quarantineID)
	return nil
}

func (q *DarwinFileQuarantine) List() ([]collector.QuarantinedFile, error) {
	q.mu.Lock()
	defer q.mu.Unlock()

	result := make([]collector.QuarantinedFile, 0, len(q.index))
	for _, f := range q.index {
		result = append(result, *f)
	}
	return result, nil
}

func generateDarwinID() string {
	out, err := exec.Command("uuidgen").Output()
	if err != nil {
		return fmt.Sprintf("%d", 0)
	}
	return strings.TrimSpace(strings.ToLower(string(out)))
}
