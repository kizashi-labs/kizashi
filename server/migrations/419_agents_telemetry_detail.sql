-- 365: agents.telemetry_detail — エージェントが報告するセンサー別の内訳。
--
-- telemetry_mode (migration 357) は集約値で、意図的に悲観的である: センサーが1つでも
-- 降格していればエージェント全体が 'poll' になる。アラートとしてはそれが正しいが、
-- 診断としては役に立たない。運用者は 'poll' を見ても「どのセンサーが、なぜ落ちたか」を
-- 知るためにホストへログインするしかない。
--
-- 実例(2026-08-03): Linux エージェントで eBPF のファイル監視とネットワーク監視の両方が
-- 動いておらず、T1046 が原理的に検知不能・ランサム検知がプロセス特定不可の状態で数日
-- 稼働していた。しかも降格の警告を出すコード自体が入っていないビルドだったため、ログには
-- 何も出なかった。集約値だけでは「poll である」ことしか分からず、そこから先は毎回
-- bpftool link show を叩く作業になる。
--
-- 内訳は人間向けの自由形式文字列（例: "file=poll(eBPF非対応) network=ebpf process=ebpf"）。
-- 判定・アラートは telemetry_mode で行い、この列はその理由を説明するために持つ。
ALTER TABLE agents ADD COLUMN IF NOT EXISTS telemetry_detail TEXT;
